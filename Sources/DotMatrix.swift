    // Les vrais panneaux LED ignorent les accents : nous aussi
    static func normalize(_ text: String) -> String {
        var s = text.folding(options: .diacriticInsensitive, locale: Locale(identifier: "fr_FR"))
            .uppercased()
        s = s.replacingOccurrences(of: "Œ", with: "OE")
            .replacingOccurrences(of: "…", with: "...")
            .replacingOccurrences(of: "’", with: "'")
        return String(s.map { glyphs[$0] != nil ? $0 : " " })
    }

    static func textWidth(_ normalized: String, pitch: CGFloat) -> CGFloat {
        CGFloat(normalized.count) * 6 * pitch
    }

    /// Texte en pastilles lumineuses, halo compris (fond transparent)
    static func image(_ normalized: String, pitch: CGFloat, dot: CGFloat, color: NSColor) -> CGImage? {
        let size = NSSize(width: max(1, textWidth(normalized, pitch: pitch)), height: 7 * pitch)
        let img = NSImage(size: size)
        img.lockFocus()
        let shadow = NSShadow()
        shadow.shadowColor = color.withAlphaComponent(0.85)
        shadow.shadowBlurRadius = dot * 0.9
        shadow.set()
        color.setFill()
        let inset = (pitch - dot) / 2
        for (i, ch) in normalized.enumerated() {
            guard let rows = glyphs[ch] else { continue }
            for (r, bits) in rows.enumerated() where bits != 0 {
                let y = CGFloat(6 - r) * pitch + inset
                for c in 0..<5 where bits & (1 << (4 - c)) != 0 {
                    let x = CGFloat(i * 6 + c) * pitch + inset
                    NSBezierPath(ovalIn: NSRect(x: x, y: y, width: dot, height: dot)).fill()
                }
            }
        }
        img.unlockFocus()
        var r = CGRect(origin: .zero, size: size)
        return img.cgImage(forProposedRect: &r, context: nil, hints: nil)
    }

    /// Grille de pastilles éteintes : le fond du panneau
    static func grid(cols: Int, rows: Int, pitch: CGFloat, dot: CGFloat, color: NSColor) -> CGImage? {
        let size = NSSize(width: CGFloat(cols) * pitch, height: CGFloat(rows) * pitch)
        let img = NSImage(size: size)
        img.lockFocus()
        color.setFill()
        let inset = (pitch - dot) / 2
        for r in 0..<rows {
            for c in 0..<cols {
                NSBezierPath(ovalIn: NSRect(x: CGFloat(c) * pitch + inset,
                                            y: CGFloat(r) * pitch + inset,
                                            width: dot, height: dot)).fill()
            }
        }
        img.unlockFocus()
        var rect = CGRect(origin: .zero, size: size)
        return img.cgImage(forProposedRect: &rect, context: nil, hints: nil)
    }
